test('external updates refresh, invalid updates are rejected, and stale saves conflict', async ({ page, request }) => {
  const created = await (await request.post('/api/projects', { data: { name: 'External change test', runtime: 'chatgpt' } })).json();
  await page.goto(`/#project=${created.id}`); await expect(page.getByText('PROJECT LIBRARY')).toBeVisible();
  const filename = path.resolve('data/e2e-projects', created.id, 'project.json');
  const first = JSON.parse(await fs.readFile(filename, 'utf8')); first.name = 'Changed outside the editor'; first.revision++;
  await fs.writeFile(filename, JSON.stringify(first, null, 2));
  await expect(page.getByRole('button', { name: 'Changed outside the editor' })).toBeVisible();
  const stale = await request.put(`/api/projects/${created.id}`, { data: created }); expect(stale.status()).toBe(409);
  await fs.writeFile(filename, '{ invalid JSON');
  await expect(page.getByText(/External project change rejected/)).toBeVisible();
  await fs.writeFile(filename, JSON.stringify(first, null, 2));
});

